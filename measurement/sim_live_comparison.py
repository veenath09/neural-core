
"""C3-15: Simulator-versus-live execution comparison.

Compares matched execution attempts from historical
simulation and independently collected live results.

Reports success agreement and execution-cost differences
for each RouterBench task type.

IMPORTANT:
- This module does not call any model providers.
- Simulation records are never treated as live results.
- Live records require explicit verification provenance.
- Comparisons require the same prompt, step, and model.
- Repeated attempts are distinguished by decision_index.
- Missing or mismatched executions cause explicit errors.

Real live evaluations and their ground-truth verification
must be collected separately before drawing conclusions.
"""

from __future__ import annotations

import math
from typing import Any

import numpy as np
import pandas as pd

from data.routerbench import SOURCES


BASE_KEYS = (
    "episode_id",
    "policy",
    "decision_index",
)

OPTIONAL_KEYS = (
    "onboarding_phase",
    "split",
    "seed",
    "run_id",
)

IDENTITY_FIELDS = (
    "step_id",
    "prompt_id",
    "step_type",
    "model_id",
    "round",
)

REQUIRED_FIELDS = {
    *BASE_KEYS,
    "step_id",
    "prompt_id",
    "step_type",
    "model_id",
    "executed",
    "selected_model_correct",
    "execution_cost_usd",
    "measurement_source",
}

LIVE_PROVENANCE_FIELDS = {
    "verification_method",
    "cost_source",
}


def prepare_simulator_records(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    """Mark existing evaluation records as simulation.

    This is only for records actually generated by the
    simulator. It must never be applied to live results.
    """

    if not isinstance(predictions, pd.DataFrame):
        raise TypeError(
            "predictions must be a DataFrame"
        )

    result = predictions.copy()

    if "measurement_source" in result.columns:
        if not result[
            "measurement_source"
        ].eq("simulator").all():
            raise ValueError(
                "Cannot relabel non-simulator records"
            )

    else:
        result["measurement_source"] = "simulator"

    return result


def _require_columns(
    frame: pd.DataFrame,
    required: set[str],
    label: str,
) -> None:
    missing = required.difference(
        frame.columns
    )

    if missing:
        raise ValueError(
            f"{label} missing columns: {sorted(missing)}"
        )


def _validate_text_column(
    frame: pd.DataFrame,
    column: str,
    label: str,
) -> None:
    if not frame[column].map(
        lambda value: (
            isinstance(value, str)
            and bool(value.strip())
        )
    ).all():
        raise ValueError(
            f"{label}: invalid {column}"
        )


def _validate_integer_column(
    frame: pd.DataFrame,
    column: str,
    label: str,
    *,
    maximum: int | None = None,
) -> None:
    def valid(value: Any) -> bool:
        if (
            isinstance(value, (bool, np.bool_))
            or not isinstance(
                value,
                (int, np.integer),
            )
        ):
            return False

        number = int(value)

        if number < 0:
            return False

        return maximum is None or number <= maximum

    if not frame[column].map(valid).all():
        raise ValueError(
            f"{label}: invalid {column}"
        )


def _validate_boolean_column(
    frame: pd.DataFrame,
    column: str,
    label: str,
) -> None:
    if not frame[column].map(
        lambda value: isinstance(
            value,
            (bool, np.bool_),
        )
    ).all():
        raise ValueError(
            f"{label}: {column} must contain booleans"
        )


def _validate_costs(
    frame: pd.DataFrame,
    label: str,
) -> None:
    values = frame[
        "execution_cost_usd"
    ].tolist()

    for value in values:
        if (
            isinstance(value, (bool, np.bool_))
            or not isinstance(
                value,
                (int, float, np.integer, np.floating),
            )
            or not math.isfinite(float(value))
            or float(value) < 0
        ):
            raise ValueError(
                f"{label}: invalid execution_cost_usd"
            )


def _validate_records(
    frame: pd.DataFrame,
    *,
    expected_source: str,
) -> pd.DataFrame:
    """Validate one side of the comparison."""

    if not isinstance(frame, pd.DataFrame):
        raise TypeError(
            f"{expected_source} records must be a DataFrame"
        )

    _require_columns(
        frame,
        REQUIRED_FIELDS,
        expected_source,
    )

    if expected_source == "live":
        _require_columns(
            frame,
            LIVE_PROVENANCE_FIELDS,
            "live",
        )

    if not frame[
        "measurement_source"
    ].eq(expected_source).all():
        raise ValueError(
            f"Expected {expected_source} measurement_source"
        )

    # Validate execution flags before filtering.
    # Non-executed decisions are not model observations.
    _validate_boolean_column(
        frame,
        "executed",
        expected_source,
    )

    executed = frame.loc[
        frame["executed"]
    ].copy()

    if executed.empty:
        raise ValueError(
            f"No executed {expected_source} records"
        )

    for column in (
        "episode_id",
        "policy",
        "step_id",
        "prompt_id",
        "model_id",
    ):
        _validate_text_column(
            executed,
            column,
            expected_source,
        )

    _validate_integer_column(
        executed,
        "decision_index",
        expected_source,
    )

    _validate_integer_column(
        executed,
        "step_type",
        expected_source,
        maximum=len(SOURCES) - 1,
    )

    if "round" in executed.columns:
        _validate_integer_column(
            executed,
            "round",
            expected_source,
        )

    _validate_boolean_column(
        executed,
        "selected_model_correct",
        expected_source,
    )

    _validate_costs(
        executed,
        expected_source,
    )

    if expected_source == "live":
        for column in LIVE_PROVENANCE_FIELDS:
            _validate_text_column(
                executed,
                column,
                "live",
            )

    return executed


def _comparison_keys(
    simulator: pd.DataFrame,
    live: pd.DataFrame,
) -> list[str]:
    """Choose identical attempt identifiers on both sides."""

    keys = list(BASE_KEYS)

    for column in OPTIONAL_KEYS:
        in_simulator = column in simulator.columns
        in_live = column in live.columns

        if in_simulator != in_live:
            raise ValueError(
                f"Both datasets must include {column}, "
                "or both must omit it"
            )

        if in_simulator:
            keys.append(column)

    return keys


def compare_sim_live(
    simulator: pd.DataFrame,
    live: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Compare exactly matched executed model attempts.

    Returns:
        paired: one row per matched execution attempt
        summary: success and cost metrics per task source

    The caller must supply independently collected live
    results with truthful verification and cost provenance.
    """

    sim = _validate_records(
        simulator,
        expected_source="simulator",
    )

    observed = _validate_records(
        live,
        expected_source="live",
    )

    keys = _comparison_keys(
        sim,
        observed,
    )

    for label, frame in (
        ("simulator", sim),
        ("live", observed),
    ):
        if frame[keys].isna().any().any():
            raise ValueError(
                f"{label}: missing comparison identifiers"
            )

        if frame.duplicated(
            subset=keys
        ).any():
            raise ValueError(
                f"{label}: duplicate execution identifiers"
            )

    joined = sim.merge(
        observed,
        on=keys,
        how="outer",
        suffixes=("_sim", "_live"),
        indicator=True,
        validate="one_to_one",
    )

    if not joined["_merge"].eq("both").all():
        missing_live = int(
            joined["_merge"].eq(
                "left_only"
            ).sum()
        )

        missing_sim = int(
            joined["_merge"].eq(
                "right_only"
            ).sum()
        )

        raise ValueError(
            "Execution sets differ: "
            f"{missing_live} missing live attempts, "
            f"{missing_sim} missing simulator attempts"
        )

    # Verify that every paired execution truly refers
    # to the same prompt, step, and model.
    for column in IDENTITY_FIELDS:

        in_sim = f"{column}_sim" in joined.columns
        in_live = f"{column}_live" in joined.columns

        if in_sim != in_live:
            raise ValueError(
                f"Identity field {column} differs "
                "between dataset schemas"
            )

        if in_sim:
            equal = joined[
                f"{column}_sim"
            ].eq(
                joined[f"{column}_live"]
            )

            if not equal.all():
                raise ValueError(
                    f"Execution identity mismatch: {column}"
                )

    paired = joined.drop(
        columns=["_merge"]
    ).copy()

    paired["step_type"] = paired[
        "step_type_sim"
    ].astype(int)

    paired["source"] = paired[
        "step_type"
    ].map(
        dict(enumerate(SOURCES))
    )

    paired["sim_success"] = paired[
        "selected_model_correct_sim"
    ].astype(bool)

    paired["live_success"] = paired[
        "selected_model_correct_live"
    ].astype(bool)

    paired["success_agreement"] = (
        paired["sim_success"]
        == paired["live_success"]
    )

    paired["sim_cost_usd"] = paired[
        "execution_cost_usd_sim"
    ].astype(float)

    paired["live_cost_usd"] = paired[
        "execution_cost_usd_live"
    ].astype(float)

    paired["cost_difference_usd"] = (
        paired["live_cost_usd"]
        - paired["sim_cost_usd"]
    )

    paired["absolute_cost_error_usd"] = (
        paired["cost_difference_usd"].abs()
    )

    # Keep repeat attempts separate. Do not deduplicate
    # by prompt_id or step_id.
    summary_rows = []

    for source_index, source in enumerate(SOURCES):

        group = paired.loc[
            paired["step_type"] == source_index
        ]

        if group.empty:
            continue

        summary_rows.append(
            {
                "step_type": source_index,
                "source": source,
                "executions": int(len(group)),
                "success_agreement": float(
                    group["success_agreement"].mean()
                ),
                "sim_success_rate": float(
                    group["sim_success"].mean()
                ),
                "live_success_rate": float(
                    group["live_success"].mean()
                ),
                "sim_mean_cost_usd": float(
                    group["sim_cost_usd"].mean()
                ),
                "live_mean_cost_usd": float(
                    group["live_cost_usd"].mean()
                ),
                "cost_mae_usd": float(
                    group[
                        "absolute_cost_error_usd"
                    ].mean()
                ),
                "mean_cost_difference_usd": float(
                    group["cost_difference_usd"].mean()
                ),
                "sim_total_cost_usd": float(
                    group["sim_cost_usd"].sum()
                ),
                "live_total_cost_usd": float(
                    group["live_cost_usd"].sum()
                ),
            }
        )

    summary = pd.DataFrame(
        summary_rows
    ).sort_values(
        "step_type"
    ).reset_index(
        drop=True
    )

    return paired, summary
